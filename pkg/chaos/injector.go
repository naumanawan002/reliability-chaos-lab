package chaos

import (
	"encoding/json"
	"math/rand"
	"net/http"
	"sync"
	"time"
)

// Config controls active chaos injection parameters.
type Config struct {
	LatencyMs   int     `json:"latency_ms"`   // Delay added to requests
	ErrorRate   float64 `json:"error_rate"`   // 0.0 to 1.0 (e.g. 0.3 = 30% failure)
	ErrorStatus int     `json:"error_status"` // HTTP status code returned (e.g. 500, 503)
	Enabled     bool    `json:"enabled"`
}

// Injector is the chaos middleware.
type Injector struct {
	mu     sync.RWMutex
	config Config
}

func NewInjector() *Injector {
	return &Injector{
		config: Config{
			ErrorStatus: http.StatusInternalServerError,
		},
	}
}

func (inj *Injector) SetConfig(c Config) {
	inj.mu.Lock()
	defer inj.mu.Unlock()
	if c.ErrorStatus == 0 {
		c.ErrorStatus = http.StatusInternalServerError
	}
	inj.config = c
}

func (inj *Injector) GetConfig() Config {
	inj.mu.RLock()
	defer inj.mu.RUnlock()
	return inj.config
}

// Middleware intercepts HTTP calls and injects simulated latency or faults.
func (inj *Injector) Middleware(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		cfg := inj.GetConfig()

		if cfg.Enabled {
			// 1. Latency injection
			if cfg.LatencyMs > 0 {
				time.Sleep(time.Duration(cfg.LatencyMs) * time.Millisecond)
			}

			// 2. Fault / Error rate injection
			if cfg.ErrorRate > 0 && rand.Float64() < cfg.ErrorRate {
				w.Header().Set("X-Chaos-Injected", "true")
				w.Header().Set("Content-Type", "application/json")
				w.WriteHeader(cfg.ErrorStatus)
				_ = json.NewEncoder(w).Encode(map[string]any{
					"error":   "chaos_fault_injected",
					"message": "Simulated infrastructure failure generated by chaos injector",
					"status":  cfg.ErrorStatus,
				})
				return
			}
		}

		next.ServeHTTP(w, r)
	})
}
